"""Reference implementation of the Find Hub beacon maths, for the host tests.

The EID part follows FMDNCrypto/eid_generator.py of GoogleFindMyTools
(GPL-3.0, Leon Böttger) line for line; the rest (hashed flags, advert, NRPA)
mirrors components/kfind/src/kfind.c so the C code is checked against an
independent implementation built on pycryptodomex and ecdsa.

    python3 fhn_ref.py vectors > ../../tests/host/vectors.h
    python3 fhn_ref.py eid <eik-hex> <beacon-time>
"""
import hashlib
import sys

from Cryptodome.Cipher import AES
from ecdsa import SECP160r1

K = 10
ROTATION = 1 << K


def calc_r(eik: bytes, ts: int) -> int:
    ts &= ~((1 << K) - 1)
    tsb = ts.to_bytes(4, "big")
    data = b"\xff" * 11 + bytes([K]) + tsb + b"\x00" * 11 + bytes([K]) + tsb
    rd = AES.new(eik, AES.MODE_ECB).encrypt(data)
    return int.from_bytes(rd, "big") % SECP160r1.order


def eid(eik: bytes, ts: int) -> bytes:
    r = calc_r(eik, ts)
    return (r * SECP160r1.generator).x().to_bytes(20, "big")


def hashed_flags(eik: bytes, ts: int, batt: int, utp: bool) -> int:
    r = calc_r(eik, ts)
    rb = (r % (1 << 160)).to_bytes(20, "big")  # truncated to the curve size
    flags = ((batt & 3) << 5) | (0x80 if utp else 0)
    return flags ^ hashlib.sha256(rb).digest()[-1]


def adv(e: bytes, utp: bool, flags_byte) -> bytes:
    body = bytes([0x16, 0xAA, 0xFE, 0x41 if utp else 0x40]) + e
    if flags_byte is not None:
        body += bytes([flags_byte])
    return bytes([0x02, 0x01, 0x06, len(body)]) + body


def nrpa(e: bytes) -> bytes:
    a = bytearray(hashlib.sha256(e).digest()[:6])
    a[0] &= 0x3F
    rnd = int.from_bytes(a, "big") & ((1 << 46) - 1)
    if rnd == 0 or rnd == (1 << 46) - 1:
        a[5] ^= 1
    return bytes(a)


def haystack_adv(key: bytes) -> bytes:
    """OpenHaystack Firmware/ESP32 openhaystack_main.c, as its set_payload_from_key."""
    return bytes([0x1E, 0xFF, 0x4C, 0x00, 0x12, 0x19, 0x00]) + key[6:28] + bytes([key[0] >> 6, 0x00])


def haystack_addr(key: bytes) -> bytes:
    return bytes([key[0] | 0xC0]) + key[1:6]


def c_bytes(b: bytes) -> str:
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}"


def vectors():
    cases = [
        (bytes(range(32)), 0, 1, True),
        (bytes(range(32)), 1023, 2, False),
        (bytes(range(32)), 1024, 0, True),
        (bytes([0xA5] * 32), 0x13F9EA80, 3, False),
        (hashlib.sha256(b"kode dot").digest(), 345600 + 77, 1, True),
        (hashlib.sha256(b"find hub").digest(), 0xFFFFFFFF, 1, False),
    ]
    print("/* Generated by tools/reference/fhn_ref.py vectors. Do not edit. */")
    print("#include <stdint.h>")
    print("typedef struct { uint8_t eik[32]; uint32_t ts; uint8_t batt; uint8_t utp;")
    print("                 uint8_t eid[20]; uint8_t hashed; uint8_t adv[29]; uint8_t addr[6]; } vec_t;")
    print("static const vec_t s_vec[] = {")
    for eik, ts, batt, utp in cases:
        e = eid(eik, ts)
        h = hashed_flags(eik, ts, batt, utp)
        print(f"  {{ {c_bytes(eik)}, {ts}u, {batt}, {int(utp)},")
        print(f"    {c_bytes(e)}, 0x{h:02x},")
        print(f"    {c_bytes(adv(e, utp, h))},")
        print(f"    {c_bytes(nrpa(e))} }},")
    print("};")
    print("typedef struct { uint8_t key[28]; uint8_t adv[31]; uint8_t addr[6]; } hvec_t;")
    print("static const hvec_t s_hvec[] = {")
    for seed in (b"haystack 1", b"haystack 2", b"\xff" * 4):
        key = hashlib.sha256(seed).digest()[:28]
        print(f"  {{ {c_bytes(key)}, {c_bytes(haystack_adv(key))}, {c_bytes(haystack_addr(key))} }},")
    print("};")


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "vectors":
        vectors()
    elif len(sys.argv) == 4 and sys.argv[1] == "eid":
        print(eid(bytes.fromhex(sys.argv[2]), int(sys.argv[3])).hex())
    else:
        print(__doc__)
        sys.exit(2)
